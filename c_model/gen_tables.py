"""Writes the tables of the pipelined CORDIC for the C model and the VHDL package.

Usage: gen_tables.py [--check]
"""

import sys

sys.dont_write_bytecode = True

import math
from pathlib import Path

TABLE_WIDTH = 32
TABLE_SIZE = 32
MAX_RM_GAIN = 12

# Gain-removal terms per RM_GAIN, in the order of the circular blocks of
# cordic_int_rm_gain() in c_octave/cordic_iterative.c: +n adds and -n subtracts
# (v >> n).
RM_GAIN_SHIFTS = {
    1:  [+1],
    2:  [+1, -4],
    3:  [+1, +3, -5],
    4:  [+1, +3, -6, -8],
    5:  [+1, +3, -6, -9, -12],
    6:  [+1, +3, -6, -9, -13, -14],
    7:  [+1, +3, -6, -9, -13, -14, -17],
    8:  [+1, +3, -6, -9, -13, -14, +16, -19],
    9:  [+1, +3, -6, -9, -13, -14, +16, -20, -22],
    10: [+1, +3, -6, -9, -13, -14, +16, -20, -23, -25],
    11: [+1, +3, -6, -9, -13, -14, +16, -20, -23, -26, -27],
    12: [+1, +3, -6, -9, -13, -14, +16, -20, -23, -26, -28, -29],
}

# The same terms as (sign, shift).
RM_GAIN_TERMS = {
    r: [(1 if s > 0 else -1, abs(s)) for s in shifts]
    for r, shifts in RM_GAIN_SHIFTS.items()
}

TERMS_PER_LINE = 6

ROOT = Path(__file__).resolve().parent.parent
C_PATH = ROOT / "c_model" / "cordic_pipeline_tables.h"
VHDL_PATH = ROOT / "rtl" / "vhdl" / "cordic_pipeline_pkg.vhd"

GENERATED = "Generated by c_model/gen_tables.py. Do not edit."


def atan_table():
    """atan(2^-i) in binary angle units, 2^TABLE_WIDTH is a full circle."""
    return [round(math.atan(2.0 ** -i) / (2 * math.pi) * 2 ** TABLE_WIDTH)
            for i in range(TABLE_SIZE)]


def term_lines(cells):
    """Joins the cells of a table row into lines of TERMS_PER_LINE cells."""
    return [", ".join(cells[i:i + TERMS_PER_LINE])
            for i in range(0, len(cells), TERMS_PER_LINE)]


def c_text():
    lines = [
        "/*",
        " * This file is part of YAC - Yet Another CORDIC Core",
        " * Copyright (c) 2014, Author(s), All rights reserved.",
        " *",
        " * YAC is free software; you can redistribute it and/or modify it under",
        " * the terms of the GNU Lesser General Public License as published by",
        " * the Free Software Foundation; either version 3.0 of the License, or",
        " * (at your option) any later version. YAC is distributed in the hope",
        " * that it will be useful, but WITHOUT ANY WARRANTY; without even the",
        " * implied warranty of MERCHANTABILITY or FITNESS FOR A PARTICULAR",
        " * PURPOSE. See the GNU Lesser General Public License for more details.",
        " */",
        "",
        "/**",
        " * @file cordic_pipeline_tables.h",
        " * @brief Tables of the pipelined CORDIC.",
        " * " + GENERATED,
        " */",
        "",
        "#ifndef CORDIC_PIPELINE_TABLES_H_",
        "#define CORDIC_PIPELINE_TABLES_H_",
        "",
        "#include <stdint.h>",
        "",
        "/** Bits of an entry of cordic_pipeline_atan. */",
        "#define CORDIC_PIPELINE_TABLE_WIDTH %d" % TABLE_WIDTH,
        "/** Entries of cordic_pipeline_atan. */",
        "#define CORDIC_PIPELINE_TABLE_SIZE %d" % TABLE_SIZE,
        "/** Largest RM_GAIN. */",
        "#define CORDIC_PIPELINE_MAX_RM_GAIN %d" % MAX_RM_GAIN,
        "",
        "/** Term of the gain removal: sign * (v >> shift). */",
        "typedef struct {",
        "  int8_t sign;",
        "  uint8_t shift;",
        "} cordic_pipeline_term_t;",
        "",
        "/** round(atan(2^-i) / (2 * pi) * 2^CORDIC_PIPELINE_TABLE_WIDTH). */",
        "static const uint32_t cordic_pipeline_atan[CORDIC_PIPELINE_TABLE_SIZE] = {",
    ]
    words = ["0x%08XU," % v for v in atan_table()]
    for i in range(0, len(words), 5):
        lines.append("    " + " ".join(words[i:i + 5]))
    lines += [
        "};",
        "",
        "/** Row R holds the R terms of RM_GAIN = R. Row 0 is empty. */",
        "/* clang-format off */",
        "static const cordic_pipeline_term_t",
        "    cordic_pipeline_terms[CORDIC_PIPELINE_MAX_RM_GAIN + 1]",
        "                         [CORDIC_PIPELINE_MAX_RM_GAIN] = {",
        "    {{ 0,  0}},",
    ]
    for r in range(1, MAX_RM_GAIN + 1):
        rows = term_lines([f"{{{s:+d}, {n:2d}}}" for s, n in RM_GAIN_TERMS[r]])
        lines.append("    {" + ",\n     ".join(rows) + "},")
    lines += [
        "};",
        "/* clang-format on */",
        "",
        "#endif /* CORDIC_PIPELINE_TABLES_H_ */",
        "",
    ]
    return "\n".join(lines)


