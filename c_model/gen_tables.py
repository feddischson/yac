def vhdl_text():
    lines = vhdl_header() + [
        "",
        "library ieee;",
        "use ieee.std_logic_1164.all;",
        "use ieee.numeric_std.all;",
        "",
        "package cordic_pipeline_pkg is",
        "",
        "   constant ATAN_TABLE_WIDTH : natural := %d;" % TABLE_WIDTH,
        "   constant ATAN_TABLE_SIZE  : natural := %d;" % TABLE_SIZE,
        "   constant MAX_RM_GAIN      : natural := %d;" % MAX_RM_GAIN,
        "",
        "   type atan_table_t is array( 0 to ATAN_TABLE_SIZE-1 ) of unsigned( ATAN_TABLE_WIDTH-1 downto 0 );",
        "",
        "   type rm_gain_term_t is record",
        "      add   : boolean;",
        "      shift : natural;",
        "   end record rm_gain_term_t;",
        "",
        "   type rm_gain_terms_t is array( 1 to MAX_RM_GAIN, 1 to MAX_RM_GAIN ) of rm_gain_term_t;",
        "",
        "   constant ADD     : boolean        := true;",
        "   constant SUB     : boolean        := false;",
        "   constant NO_TERM : rm_gain_term_t := ( ADD, 0 );",
        "",
        "   -- round( atan( 2**-i ) / ( 2*pi ) * 2**ATAN_TABLE_WIDTH )",
        "   constant ATAN_TABLE : atan_table_t := (",
    ]
    t = atan_table()
    for i, v in enumerate(t):
        sep = "," if i < len(t) - 1 else ""
        lines.append("      x\"%08X\"%s" % (v, sep))
    lines += [
        "   );",
        "",
        "   -- Row R holds the R terms of RM_GAIN = R: ( ADD or SUB, shift ) of v >> shift.",
        "   constant RM_GAIN_TERMS : rm_gain_terms_t := (",
    ]
    for r in range(1, MAX_RM_GAIN + 1):
        cells = [f"( {'ADD' if s > 0 else 'SUB'}, {n:2d} )"
                 for s, n in RM_GAIN_TERMS[r]]
        rows = term_lines(cells)
        if r < MAX_RM_GAIN:
            rows[-1] += ", others => NO_TERM"
        tail = "," if r < MAX_RM_GAIN else ""
        lines.append(f"      {r:<2d} => ( " + ",\n              ".join(rows)
                     + f" ){tail}")
    lines += [
        "   );",
        "",
        "   function cordic_pipeline_latency( N_ITER, RM_GAIN : natural ) return natural;",
        "",
        "end package cordic_pipeline_pkg;",
        "",
        "package body cordic_pipeline_pkg is",
        "",
        "   function cordic_pipeline_latency( N_ITER, RM_GAIN : natural ) return natural is",
        "   begin",
        "      return 1 + N_ITER + RM_GAIN;",
        "   end function cordic_pipeline_latency;",
        "",
        "end package body cordic_pipeline_pkg;",
        "",
    ]
    return "\n".join(lines)


def main(argv):
    outputs = {C_PATH: c_text(), VHDL_PATH: vhdl_text()}
    if "--check" in argv:
        for path, text in outputs.items():
            if not path.exists() or path.read_text() != text:
                print("%s is not current" % path, file=sys.stderr)
                return 1
        return 0
    for path, text in outputs.items():
        path.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
